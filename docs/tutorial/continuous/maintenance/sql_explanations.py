def table_parts(source):
    match = re.search(r'CREATE\s+TABLE\s+`?\w+`?\s*\(', source, re.I)
    if not match:
        return []
    start = match.end()
    depth, quote, escaped = 0, None, False
    parts = []
    i = start
    while i < len(source):
        char = source[i]
        if quote:
            if escaped:
                escaped = False
            elif char == '\\':
                escaped = True
            elif char == quote:
                if i+1 < len(source) and source[i+1] == quote:
                    i += 1
                else:
                    quote = None
        elif char in "'\"`":
            quote = char
        elif char == '(':
            depth += 1
        elif char == ')':
            if depth == 0:
                parts.append(source[start:i].strip())
                return parts
            depth -= 1
        elif char == ',' and depth == 0:
            parts.append(source[start:i].strip())
            start = i+1
        i += 1
    raise ValueError('SQL_CREATE_TABLE_UNCLOSED')


