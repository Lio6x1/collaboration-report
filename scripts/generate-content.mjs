import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import Ajv2020 from 'ajv/dist/2020.js';
import standalone from 'ajv/dist/standalone/index.js';
import { loadContentContract } from './load-content-contract.mjs';
const schema = loadContentContract(fileURLToPath(new URL('..', import.meta.url)));
// 构建时合并冻结schema和受限段落扩展；浏览器和Node共用结果，浏览器无需unsafe-eval。
const ajv = new Ajv2020({
    strict: false,
    allErrors: false,
    code: { source: true, esm: true, lines: true },
  }),
  validate = ajv.compile(schema);
let source = standalone(ajv, validate);
source = source.replace(
  /const (\w+) = require\("ajv\/dist\/runtime\/ucs2length"\)\.default;/g,
  (_m, name) =>
    `import ${name}Runtime from 'ajv/dist/runtime/ucs2length.js';\nconst ${name}=${name}Runtime.default??${name}Runtime;`,
);
if (source.includes('require(')) throw Error('VALIDATOR_RUNTIME_IMPORT_UNRECOGNIZED');
const output = new URL('../packages/content/validate.mjs', import.meta.url),
  expected = '// Generated by scripts/generate-content.mjs; do not edit.\n' + source;
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== expected) throw Error('CONTENT_VALIDATOR_STALE');
  console.log('CONTENT_VALIDATOR_MATCHES_SCHEMA');
} else {
  writeFileSync(output, expected);
  console.log('CONTENT_VALIDATOR_GENERATED');
}
